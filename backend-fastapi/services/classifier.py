from __future__ import annotations
from dataclasses import dataclass
from typing import List, Tuple
import os
import time


WASTE_CATEGORIES = [
    "Plastic",
    "Paper",
    "Metal",
    "Glass",
    "Organic",
    "Non-Recyclable",
]


@dataclass
class ClassificationResult:
    waste_type: str
    detected_item: str
    confidence: float
    visual_cues: List[str]
    ai_explanation: str
    prediction_source: str
    inference_time_ms: int
    last_conv_activation_box: Tuple[int, int, int, int]


class WasteClassifierService:
    """
    Modular AI classification interface.
    """

    def predict(self, image_bytes: bytes) -> ClassificationResult:
        raise NotImplementedError


class TrainedMobileNetV2Classifier(WasteClassifierService):
    """
    Production slot for PyTorch/Torchvision MobileNetV2 fine-tuned on TrashNet/TACO.
    """

    def __init__(self, weights_path: str = "models/mobilenetv2_recycleiq.pth") -> None:
        self.weights_path = weights_path
        if not os.path.exists(weights_path):
            raise FileNotFoundError(
                f"Trained weights not found at {weights_path}. Use PrototypeClassifier or Groq API during development."
            )

    def predict(self, image_bytes: bytes) -> ClassificationResult:
        raise NotImplementedError("Attach trained MobileNetV2 checkpoint for local tensor inference.")


class PrototypeClassifier(WasteClassifierService):
    """
    Local development fallback when a trained .pth/.h5 model is not mounted.
    """

    def predict(self, image_bytes: bytes) -> ClassificationResult:
        started = time.perf_counter()
        elapsed_ms = max(12, int((time.perf_counter() - started) * 1000))
        return ClassificationResult(
            waste_type="Plastic",
            detected_item="Development sample waste item",
            confidence=86.4,
            visual_cues=[
                "Development fallback active",
                "Central object region analyzed for contour and surface texture",
            ],
            ai_explanation=(
                "This prediction was generated by the local FastAPI fallback. "
                "Use the Groq vision API endpoint or mount trained MobileNetV2 weights for live inference."
            ),
            prediction_source="FastAPI Local Fallback",
            inference_time_ms=elapsed_ms,
            last_conv_activation_box=(220, 220, 780, 780),
        )
